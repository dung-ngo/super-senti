export function playVictoryFanfare(enabled = true): void {
  if (!enabled) return;
  try {
    const ctx = getAudioContext();
    if (!ctx) return;

    // Upbeat 8-bit quest completion sequence
    const notes = [
      { f: 523.25, d: 0.1 },  // C5
      { f: 659.25, d: 0.1 },  // E5
      { f: 783.99, d: 0.1 },  // G5
      { f: 1046.5, d: 0.25 }, // C6
      { f: 880.0, d: 0.12 },  // A5
      { f: 1046.5, d: 0.4 },  // C6 hold
    ];

    let current = ctx.currentTime;
    notes.forEach((note) => {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();

      osc.type = 'square';
      osc.frequency.setValueAtTime(note.f, current);

      gain.gain.setValueAtTime(0.09, current);
      gain.gain.exponentialRampToValueAtTime(0.001, current + note.d);

      osc.connect(gain);
      gain.connect(ctx.destination);

      osc.start(current);
      osc.stop(current + note.d);

      current += note.d * 0.9;
    });
  } catch {
    // Silent
  }
}
